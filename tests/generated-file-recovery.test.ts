import { expect, test } from "bun:test";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { GENERATED_FILE_TTL_MS, serveGeneratedFile, storeGeneratedFile } from "../src/generated-files";

const bytes = new TextEncoder().encode("original generated bytes");
const scope = createHash("sha256").update(JSON.stringify(["account", "operation", "round", "trace"])).digest("hex");
const baseUrl = "https://downloads.example.invalid/account";

test("separate helper processes converge on one unpredictable original artifact capability", async () => {
  const directory = mkdtempSync(join(tmpdir(), "generated-recovery-"));
  try {
    const script = `import { storeGeneratedFile } from ${JSON.stringify(new URL("../src/generated-files.ts", import.meta.url).href)};
      process.stdout.write(storeGeneratedFile(${JSON.stringify(directory)}, ${JSON.stringify(baseUrl)}, "report.txt", "text/plain",
        new TextEncoder().encode("original generated bytes"), Date.now(), { recoveryScope: ${JSON.stringify(scope)} }));`;
    const helper = () => Bun.spawn([process.execPath, "-e", script], { stdout: "pipe", stderr: "pipe" });
    const first = helper(), concurrent = helper();
    const [a, b] = await Promise.all([new Response(first.stdout).text(), new Response(concurrent.stdout).text()]);
    expect(await first.exited).toBe(0); expect(await concurrent.exited).toBe(0); expect(a).toBe(b);
    const restarted = helper(); expect(await new Response(restarted.stdout).text()).toBe(a); expect(await restarted.exited).toBe(0);
    const token = new URL(a).pathname.split("/").at(-2)!;
    expect(token).toMatch(/^[a-f0-9]{64}$/); expect(token).not.toBe(scope);
    expect(token).not.toBe(createHash("sha256").update(bytes).digest("hex"));
    expect(readdirSync(directory).filter(name => /^[a-f0-9]{64}$/.test(name))).toEqual([token]);
    const otherScope = createHash("sha256").update("another-account-operation").digest("hex");
    expect(storeGeneratedFile(directory, baseUrl, "report.txt", "text/plain", bytes, Date.now(), { recoveryScope: otherScope })).not.toBe(a);
  } finally { rmSync(directory, { recursive: true, force: true }); }
});

for (const failure of ["changed-bytes", "missing-bytes", "changed-metadata", "corrupt-index", "null-index", "expired"] as const) {
  test(`an original artifact with ${failure} cannot be replaced by a newly signed recovery URL`, () => {
    const directory = mkdtempSync(join(tmpdir(), "generated-recovery-")), now = Date.now();
    try {
      const url = storeGeneratedFile(directory, "https://downloads.example.invalid", "report.txt", "text/plain", bytes, now, { recoveryScope: scope });
      const token = new URL(url).pathname.split("/").at(-2)!, path = join(directory, token);
      if (failure === "changed-bytes") writeFileSync(join(path, "content"), "x".repeat(bytes.length));
      if (failure === "missing-bytes") rmSync(join(path, "content"));
      if (failure === "changed-metadata") {
        const metadata = JSON.parse(readFileSync(join(path, "metadata.json"), "utf8"));
        writeFileSync(join(path, "metadata.json"), JSON.stringify({ ...metadata, mime: "text/html" }));
      }
      if (failure === "corrupt-index" || failure === "null-index") {
        const directoryPath = join(directory, "recovery", scope);
        writeFileSync(join(directoryPath, readdirSync(directoryPath)[0]!), failure === "null-index" ? "null" : "{broken");
      }
      expect(() => storeGeneratedFile(directory, "https://downloads.example.invalid", "report.txt", "text/plain", bytes,
        failure === "expired" ? now + GENERATED_FILE_TTL_MS : now + 1, { recoveryScope: scope })).toThrow("original generated file is unavailable");
      expect(readdirSync(directory).filter(name => /^[a-f0-9]{64}$/.test(name))).toEqual([token]);
      if (failure === "expired") expect(serveGeneratedFile(new Request(url), directory, now + GENERATED_FILE_TTL_MS)?.status).toBe(404);
    } finally { rmSync(directory, { recursive: true, force: true }); }
  });
}

test("artifact recovery indexes accept only a local digest scope", () => {
  const directory = mkdtempSync(join(tmpdir(), "generated-recovery-"));
  try {
    expect(() => storeGeneratedFile(directory, baseUrl, "report.txt", "text/plain", bytes, Date.now(), { recoveryScope: "../foreign" })).toThrow("scope");
    expect(readdirSync(directory)).toEqual([]);
  } finally { rmSync(directory, { recursive: true, force: true }); }
});
